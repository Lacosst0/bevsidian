"""Builds the note icon font: a subset of Lucide (https://lucide.dev, ISC license).

Writes `assets/fonts/Lucide.ttf` with the icons below, and the name → character table
`crates/bevsidian_core/src/icons.rs`. To offer another icon, add its Lucide name to ICONS and
run `python3 tools/icons.py` (needs `pip install fonttools`).
"""

import io
import json
import pathlib
import tarfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

VERSION = "0.468.0"
ICONS = """
archive atom bell bird book book-open bookmark box boxes brain brush bug calculator calendar
camera cat chart-bar chart-line check chevron-left chevron-right circle circle-help clapperboard
clock cloud code coffee compass component copy cpu crown cuboid database dog download feather
file-text film fish flag flame flask-conical folder gamepad-2 gem ghost git-branch github globe
graduation-cap hammer headphones heart house image info key keyboard layers layout-template leaf
library lightbulb link list list-checks lock mail map maximize message-square mic minus monitor
moon mountain mouse-pointer move music notebook-pen orbit package paintbrush palette panel-left
panel-right pause pencil pizza play plus puzzle quote rocket rotate-3d rotate-ccw scale-3d
scroll-text search send server settings shapes shield sliders-horizontal smartphone sparkles
speaker sprout star step-back step-forward sun table target terminal text tree-pine
triangle-alert trophy type upload user users video volume-2 wand-sparkles wrench x zap
arrow-down arrow-up arrow-up-right chevron-down circle-check circle-x corner-down-left ellipsis
external-link eye file filter folder-open hash square-function text-select undo-2 waypoints
chevrons-up-down chevrons-left-right braces file-code blocks file-input bot swords route workflow shuffle save crosshair footprints dices backpack message-circle vibrate languages accessibility tree-deciduous
""".split()

ROOT = pathlib.Path(__file__).resolve().parent.parent
url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz"
with urllib.request.urlopen(url) as response:
    package = tarfile.open(fileobj=io.BytesIO(response.read()))
info = json.load(package.extractfile("package/font/info.json"))
font = TTFont(io.BytesIO(package.extractfile("package/font/lucide.ttf").read()))

codes = {name: int(info[name]["encodedCode"].lstrip("\\"), 16) for name in sorted(ICONS)}
options = subset.Options()
options.layout_features = []
options.name_IDs = ["*"]
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=codes.values())
subsetter.subset(font)
font.save(ROOT / "assets/fonts/Lucide.ttf")

# Lucide's metrics give every glyph a left side bearing of 0, though the outlines start further
# right; hinting rasterizers trust the metric and draw each icon off-centre. Use the real one.
# (Done on the saved file: saving the subset font resets the bearings.)
font = TTFont(ROOT / "assets/fonts/Lucide.ttf")
glyf = font["glyf"]
for name, (advance, _) in font["hmtx"].metrics.items():
    font["hmtx"][name] = (advance, getattr(glyf[name], "xMin", 0))
font.save(ROOT / "assets/fonts/Lucide.ttf")

rows = "\n".join(f'    ("{name}", \'\\u{{{code:x}}}\'),' for name, code in codes.items())
(ROOT / "crates/bevsidian_core/src/icons.rs").write_text(
    f"""//! Note icons: Lucide {VERSION} names and their characters in `assets/fonts/Lucide.ttf`.
//! Generated by `tools/icons.py`; edit the list there.

/// Icon of notes that do not choose one.
pub const DEFAULT: char = \'\\u{{{codes["file-text"]:x}}}\';

/// The icon character for a Lucide name (e.g. `rocket`).
pub fn find(name: &str) -> Option<char> {{
    let name = name.trim();
    ICONS
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| ICONS[i].1)
}}

/// `(name, character)`, sorted by name.
pub const ICONS: &[(&str, char)] = &[
{rows}
];
"""
)
print(f"{len(codes)} icons, {(ROOT / 'assets/fonts/Lucide.ttf').stat().st_size} bytes")
